const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function validateAuthorizationId(authorizationId: string | null | undefined): {
  valid: boolean;
  error?: string;
} {
  if (!authorizationId || typeof authorizationId !== "string" || authorizationId.trim() === "") {
    return {
      valid: false,
      error: "Missing required 'authorization_id' parameter. The authorization request cannot be processed.",
    };
  }

  const trimmed = authorizationId.trim();
  if (!/^[a-zA-Z0-9_-]{10,128}$/.test(trimmed)) {
    return {
      valid: false,
      error: "Invalid authorization_id format. Must be a valid identifier generated by Supabase OAuth Server.",
    };
  }

  return { valid: true };
}

export function validateOwnerAccess(userId: string | null | undefined): {
  isOwner: boolean;
  error?: string;
} {
  if (!userId) {
    return {
      isOwner: false,
      error: "Authentication required: No active owner session found. Please sign in.",
    };
  }

  if (userId !== DESIGNATED_OWNER_UUID) {
    return {
      isOwner: false,
      error: `Access denied: User ${userId} is not the designated owner (${DESIGNATED_OWNER_UUID}). Only the owner may grant OAuth permissions.`,
    };
  }

  return { isOwner: true };
}

/**
 * Hardened redirect validator:
 * Rejects external protocols, protocol-relative paths (// or /\), backslashes,
 * and URL-encoded bypasses. Guarantees that only safe relative internal paths are returned.
 */
export function validateSafeRedirect(redirectParam: string | null | undefined, fallback: string = "/"): string {
  if (!redirectParam || typeof redirectParam !== "string") {
    return fallback;
  }

  const trimmed = redirectParam.trim();

  // Reject protocol-relative, backslash, control chars, and encoded bypasses
  if (
    !trimmed.startsWith("/") ||
    trimmed.startsWith("//") ||
    trimmed.startsWith("/\\") ||
    trimmed.includes("\\") ||
    /%5c|%2f|%00/i.test(trimmed)
  ) {
    return fallback;
  }

  try {
    const parsed = new URL(trimmed, "http://localhost");
    // Origin must match dummy origin exactly
    if (parsed.origin !== "http://localhost") {
      return fallback;
    }
    // Pathname must be relative and not contain escaping characters
    if (
      !parsed.pathname.startsWith("/") ||
      parsed.pathname.startsWith("//") ||
      parsed.pathname.includes("\\")
    ) {
      return fallback;
    }
    // Scheme must be http:
    if (parsed.protocol !== "http:") {
      return fallback;
    }

    return `${parsed.pathname}${parsed.search}${parsed.hash}`;
  } catch {
    return fallback;
  }
}

export function parseScopes(scopeString: string | null | undefined): string[] {
  if (!scopeString || typeof scopeString !== "string") {
    return ["openid"];
  }

  const parts = scopeString.split(/\s+/).filter(Boolean);
  return parts.length > 0 ? parts : ["openid"];
}

export type ClientTrustResult =
  | {
      trusted: true;
      connector: "grok" | "cursor";
      isKnownStatic: boolean;
      isDynamicRegistration: boolean;
      clientName: string;
      clientId: string;
      redirectUri: string;
      requiresInteractiveConsent: boolean;
    }
  | {
      trusted: false;
      reason: string;
      isKnownStatic?: boolean;
      connector?: "grok" | "cursor" | "untrusted";
      clientId?: string;
      redirectUri?: string;
      isPendingApproval?: boolean;
    };

/**
 * OAuth client verification:
 * Preserves dynamically registered Grok clients and allows one specifically
 * reviewed Cursor registration. Arbitrary Cursor registrations remain denied.
 *
 * Requirements:
 * 1. Valid UUID client identifier.
 * 2. Exact approved callback URI for that client.
 * 3. Grok metadata requirements or exact approved Cursor ID and name.
 * 4. Requires explicit interactive owner consent before authorization code is issued.
 */
export function validateOAuthClient(
  client: { id: string; name?: string } | null | undefined,
  redirectUri: string | null | undefined
): ClientTrustResult {
  if (!client || !client.id || !UUID_REGEX.test(client.id)) {
    return {
      trusted: false,
      reason: "Invalid or missing OAuth client identifier. Must be a valid UUID.",
      connector: "untrusted",
    };
  }

  if (!redirectUri || typeof redirectUri !== "string") {
    return {
      trusted: false,
      reason: "Missing client redirect URI.",
      connector: "untrusted",
      clientId: client.id,
    };
  }

  const trimmedRedirect = redirectUri.trim();
  const clientName = client.name?.trim() || "";

  // Cursor access is pinned to the single owner-reviewed registration. Client
  // names alone are not trusted because OAuth dynamic registration is enabled.
  if (trimmedRedirect === VERIFIED_CURSOR_CALLBACK_URI) {
    if (client.id !== APPROVED_CURSOR_CLIENT_ID || clientName !== "Cursor") {
      return {
        trusted: false,
        reason: "Cursor OAuth registration is not approved. Only the verified owner-reviewed Cursor client ID can use this callback.",
        connector: "cursor",
        clientId: client.id,
        redirectUri: trimmedRedirect,
      };
    }

    return {
      trusted: true,
      connector: "cursor",
      isKnownStatic: true,
      isDynamicRegistration: false,
      clientName,
      clientId: client.id,
      redirectUri: trimmedRedirect,
      requiresInteractiveConsent: true,
    };
  }

  // 1. Strict callback URI verification: preserve existing Grok-only policy
  if (trimmedRedirect !== VERIFIED_GROK_CALLBACK_URI) {
    return {
      trusted: false,
      reason: `Unauthorized callback URI '${trimmedRedirect}'. Only the verified Grok connector URI (${VERIFIED_GROK_CALLBACK_URI}) is permitted.`,
      connector: "untrusted",
      clientId: client.id,
      redirectUri: trimmedRedirect,
    };
  }

  // 2. Client metadata verification: must match Grok connector name
  if (!/^Grok/i.test(clientName)) {
    return {
      trusted: false,
      reason: `Mismatched client metadata. Expected Grok connector client name, but received '${clientName || "unnamed"}'.`,
      connector: "untrusted",
      clientId: client.id,
      redirectUri: trimmedRedirect,
    };
  }

  const isKnownStatic = client.id === ACTIVE_GROK_CLIENT_ID;

  return {
    trusted: true,
    connector: "grok",
    isKnownStatic,
    isDynamicRegistration: !isKnownStatic,
    clientName: client.name || "Grok",
    clientId: client.id,
    redirectUri: trimmedRedirect,
    requiresInteractiveConsent: true,
  };
}

/**
 * Validates automatic redirect URLs from previously approved OAuth grants:
 * Ensures destination is an exact allowlisted Grok or Cursor callback URI.
 */
export function validateAutoRedirectUrl(redirectUrl: string | null | undefined): {
  valid: boolean;
  error?: string;
  targetOriginPath?: string;
} {
  if (!redirectUrl || typeof redirectUrl !== "string") {
    return {
      valid: false,
      error: "Missing redirect URL in authorization response.",
    };
  }

  try {
    const parsed = new URL(redirectUrl.trim());
    const originPath = `${parsed.origin}${parsed.pathname}`;
    if (!TRUSTED_REDIRECT_URIS.includes(originPath)) {
      return {
        valid: false,
        error: `Unauthorized auto-redirect destination '${originPath}'. The redirect must match a verified connector callback.`,
        targetOriginPath: originPath,
      };
    }
    return { valid: true, targetOriginPath: originPath };
  } catch {
    return {
      valid: false,
      error: "Malformed redirect URL returned by authorization server.",
    };
  }
}
